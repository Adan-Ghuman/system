import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { uppercaseDisplay, uppercaseWorkbook } from '../server/dist/utils/uppercaseDisplay.js';
const require = createRequire(import.meta.url);
const ExcelJS = require('../server/node_modules/exceljs');
assert.equal(uppercaseDisplay('Fabric ü blue 0007/26'), 'FABRIC Ü BLUE 0007/26');
const technical = 'https://example.com/Mixed admin@example.com 507f1f77bcf86cd799439011';
assert.equal(uppercaseDisplay(technical), technical);
const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet('Source data');
const date = new Date('2026-10-20T00:00:00Z');
sheet.addRow(['Blue fabric', 12.125, date]);
sheet.getCell('A2').value = { formula: '"Mixed literal"', result: 'Mixed literal' };
sheet.getCell('B2').value = { text: 'Open document', hyperlink: 'https://example.com/Mixed' };
sheet.getCell('C2').value = { richText: [{ text: 'Mixed name', font: { bold: true } }] };
uppercaseWorkbook(workbook);
const reopened = new ExcelJS.Workbook();
await reopened.xlsx.load(await workbook.xlsx.writeBuffer());
const saved = reopened.getWorksheet('Source data');
assert.equal(saved.getCell('A1').value, 'BLUE FABRIC');
assert.equal(saved.getCell('B1').value, 12.125);
assert.equal(saved.getCell('C1').value.toISOString(), date.toISOString());
assert.equal(saved.getCell('A2').formula, '"Mixed literal"');
assert.equal(saved.getCell('A2').result, 'Mixed literal');
assert.equal(saved.getCell('B2').hyperlink, 'https://example.com/Mixed');
assert.equal(saved.getCell('B2').text, 'OPEN DOCUMENT');
assert.equal(saved.getCell('C2').value.richText[0].text, 'MIXED NAME');
console.log('PASS uppercase exports preserve numeric/date values, formulas, links and identifiers.');
